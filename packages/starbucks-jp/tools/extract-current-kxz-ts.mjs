import { createHash } from 'node:crypto'
import { gzipSync } from 'node:zlib'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { parse } from 'acorn'

/**
 * Extracts the current (WASM-less) KXZ dispatcher as data for the TypeScript
 * port.  This script only parses literals/AST; it never evaluates the vendor
 * source and never creates a WebAssembly.Module.
 *
 * Usage: node extract-current-kxz-ts.mjs <main.js> [output.ts] [instrumentation.js] [bootstrap.js]
 */
const [input, output = '/tmp/starbucks-current-kxz-data.ts', instrumentation, bootstrap] =
  process.argv.slice(2)
if (!input)
  throw new Error(
    'usage: node extract-current-kxz-ts.mjs <main.js> [output.ts] [instrumentation.js] [bootstrap.js]',
  )

const source = await readFile(resolve(input), 'utf8')
const ast = parse(source, {
  ecmaVersion: 'latest',
  allowHashBang: true,
  allowReturnOutsideFunction: true,
  sourceType: 'script',
})

const normalize = (node) => {
  if (node === null || node === undefined || typeof node !== 'object') return node
  if (Array.isArray(node)) return node.map(normalize)
  if (node.type === 'Literal') return { type: 'Literal', value: node.value }
  const result = {}
  for (const [key, value] of Object.entries(node)) {
    if (['start', 'end', 'loc', 'raw', 'regex'].includes(key)) continue
    result[key] = normalize(value)
  }
  return result
}

const literals = (node) => {
  if (node?.type === 'Literal') return node.value
  if (node?.type === 'ArrayExpression') return node.elements.map(literals)
  if (node?.type === 'ObjectExpression') {
    const result = {}
    for (const property of node.properties ?? []) {
      const key = property.key?.name ?? property.key?.value
      if (typeof key === 'string') result[key] = literals(property.value)
    }
    return result
  }
  return undefined
}

const declarations = new Map()
const visit = (node) => {
  if (!node || typeof node !== 'object') return
  if (node.type === 'VariableDeclarator' && node.id?.type === 'Identifier')
    declarations.set(node.id.name, node.init)
  for (const value of Object.values(node)) {
    if (value && typeof value === 'object') {
      if (Array.isArray(value)) value.forEach(visit)
      else visit(value)
    }
  }
}
visit(ast)

const required = (name) => {
  const node = declarations.get(name)
  if (!node) throw new Error(`current KXZ declaration ${name} was not found`)
  return node
}
const array = (name) => {
  const node = required(name)
  if (node.type !== 'ArrayExpression') throw new Error(`${name} is not an array`)
  return node
}
const handlers = array('MG').elements.map((entry, index) => {
  if (entry?.type !== 'FunctionExpression') throw new Error(`MG[${index}] is not a function`)
  return {
    params: entry.params.map((param) => {
      if (param.type !== 'Identifier')
        throw new Error(`MG[${index}] has a non-identifier parameter`)
      return param.name
    }),
    body: normalize(entry.body),
  }
})
const bytecodeNode = required('J')
if (
  bytecodeNode.type !== 'CallExpression' ||
  bytecodeNode.callee?.type !== 'Identifier' ||
  bytecodeNode.callee.name !== 'Mr' ||
  bytecodeNode.arguments[0]?.type !== 'Literal' ||
  typeof bytecodeNode.arguments[0].value !== 'string'
)
  throw new Error('J is not a static Mr(base64) call')
const bytecode = Buffer.from(bytecodeNode.arguments[0].value, 'base64')
const primitiveNode = array('b')
const primitiveNames = primitiveNode.elements.map((entry) => {
  if (entry?.type !== 'Identifier') throw new Error('b contains a non-identifier')
  return entry.name
})

const data = {
  hash: createHash('sha256').update(source).digest('hex'),
  instrumentationHash: instrumentation
    ? createHash('sha256')
        .update(await readFile(resolve(instrumentation)))
        .digest('hex')
    : undefined,
  bootstrapHash: bootstrap
    ? createHash('sha256')
        .update(await readFile(resolve(bootstrap)))
        .digest('hex')
    : undefined,
  strings: literals(array('j')),
  dispatch: literals(array('Mj')),
  metadata: literals(array('Mi')),
  numbers: literals(array('Mn')),
  handlers,
  bytecode: gzipSync(bytecode).toString('base64'),
  bytecodeLength: bytecode.length,
  primitiveNames,
}

const gzipJson = (value) => gzipSync(Buffer.from(JSON.stringify(value))).toString('base64')
const text =
  `// Generated by extract-current-kxz-ts.mjs; do not edit by hand.\n` +
  `export const STARBUCKS_CURRENT_KXZ_SCRIPT_SHA256 = ${JSON.stringify(data.hash)} as const\n` +
  (data.instrumentationHash
    ? `export const STARBUCKS_CURRENT_KXZ_INSTRUMENTATION_SHA256 = ${JSON.stringify(data.instrumentationHash)} as const\n`
    : '') +
  (data.bootstrapHash
    ? `export const STARBUCKS_CURRENT_KXZ_BOOTSTRAP_SHA256 = ${JSON.stringify(data.bootstrapHash)} as const\n`
    : '') +
  `export const STARBUCKS_CURRENT_KXZ_STRINGS_GZIP_BASE64 = ${JSON.stringify(gzipJson(data.strings))}\n` +
  `export const STARBUCKS_CURRENT_KXZ_DISPATCH_GZIP_BASE64 = ${JSON.stringify(gzipJson(data.dispatch))}\n` +
  `export const STARBUCKS_CURRENT_KXZ_METADATA_GZIP_BASE64 = ${JSON.stringify(gzipJson(data.metadata))}\n` +
  `export const STARBUCKS_CURRENT_KXZ_NUMBERS_GZIP_BASE64 = ${JSON.stringify(gzipJson(data.numbers))}\n` +
  `export const STARBUCKS_CURRENT_KXZ_HANDLER_IR_GZIP_BASE64 = ${JSON.stringify(gzipJson(data.handlers))}\n` +
  `export const STARBUCKS_CURRENT_KXZ_BYTECODE_GZIP_BASE64 = ${JSON.stringify(data.bytecode)}\n` +
  `export const STARBUCKS_CURRENT_KXZ_BYTECODE_LENGTH = ${data.bytecodeLength}\n` +
  `export const STARBUCKS_CURRENT_KXZ_PRIMITIVE_NAMES = ${JSON.stringify(data.primitiveNames)} as const\n`
await mkdir(resolve(output).replace(/\/[^/]+$/, ''), { recursive: true })
await writeFile(resolve(output), text)
console.log(
  JSON.stringify({
    output: resolve(output),
    hash: data.hash,
    handlers: handlers.length,
    bytecode: bytecode.length,
    instrumentation: data.instrumentationHash,
    bootstrap: data.bootstrapHash,
  }),
)
